import assert from 'node:assert/strict';
import {familyScope, recordsForScope, taipeiDay, taipeiDateTime, taipeiToIso, monthGrid, eventsOnDay, validateEvent, validPosition, sanitizeLocalData, escapeHtml} from '../web-model.js';

assert.equal(taipeiDay('2026-11-12T16:01:00Z'), '2026-11-13');
assert.equal(taipeiDateTime('2026-11-12T16:01:00Z'), '2026-11-13T00:01');
assert.equal(taipeiToIso('2026-11-13T08:30'), '2026-11-13T00:30:00.000Z');
assert.throws(() => taipeiToIso('2026-02-30T08:30'));
assert.throws(() => taipeiToIso('2026-11-13T24:30'));
const grid = monthGrid(2026, 10, '2026-11-13');
assert.equal(grid.length,42);
assert.equal(grid[0].key,'2026-10-26');
assert.equal(grid.filter(d=>d.inMonth).length,30);
assert.equal(grid.filter(d=>d.today).length,1);
const fields = {title:'家庭晚餐', start:'2026-11-13T18:00', end:'2026-11-13T19:00', reminder:'15'};
const event = validateEvent(fields);
assert.equal(event.starts_at,'2026-11-13T10:00:00.000Z');
assert.throws(()=>validateEvent({...fields,end:fields.start}));
assert.throws(()=>validateEvent({...fields,title:'   '}));
assert.throws(()=>validateEvent({...fields,reminder:'99'}));
const spanning = [{starts_at:'2026-11-13T15:30:00Z',ends_at:'2026-11-13T16:30:00Z'}];
assert.equal(eventsOnDay(spanning,'2026-11-13').length,1);
assert.equal(eventsOnDay(spanning,'2026-11-14').length,1);
assert.equal(eventsOnDay(spanning,'2026-11-15').length,0);
const now = Date.parse('2026-11-13T10:00:00Z');
const fix = {latitude:25.0,longitude:121.5,accuracy:10,recordedAt:new Date(now).toISOString()};
assert.equal(validPosition(fix,now),true);
assert.equal(validPosition({...fix,latitude:NaN},now),false);
assert.equal(validPosition({...fix,recordedAt:new Date(now-120001).toISOString()},now),false);
assert.equal(validPosition({...fix,recordedAt:new Date(now+10001).toISOString()},now),false);
assert.equal(sanitizeLocalData({events:[null,{},event],reports:[fix,{...fix,longitude:999}]}).reports.length,1);
assert.equal(escapeHtml('<img src=x onerror="alert(1)">'), '&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
const mixedRecords=[{id:'personal'},{id:'legacy-cloud',scope:'user-1'},{id:'family-a',scope:familyScope('user-1','a')},{id:'family-b',scope:familyScope('user-1','b')},{id:'other-user',scope:familyScope('user-2','b')}];
assert.deepEqual(recordsForScope(mixedRecords,familyScope('user-1','b')).map(record=>record.id),['family-b']);
assert.deepEqual(recordsForScope(mixedRecords,'local').map(record=>record.id),['personal']);
console.log('Web model: timezone, calendar, input validation, stored data and location freshness checks passed.');
